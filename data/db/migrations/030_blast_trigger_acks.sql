-- Batch 18E: ITB TriggerStart ACK history
-- Additive migration; existing blast/config tables remain unchanged.

BEGIN;

CREATE TABLE blast_trigger_acks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    device_id TEXT NOT NULL
        REFERENCES devices(device_id),

    pending_config_id BIGINT NOT NULL
        REFERENCES device_config_pending(id),

    trigger_start SMALLINT NOT NULL
        CHECK (trigger_start IN (0, 1)),

    received BOOLEAN NOT NULL
        CHECK (received IS TRUE),

    device_timestamp_utc TIMESTAMP,
    server_received_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    device_role TEXT NOT NULL,
    iccid TEXT NOT NULL,
    device_version TEXT NOT NULL
);

CREATE INDEX blast_trigger_acks_device_time_idx
    ON blast_trigger_acks (
        device_id,
        server_received_at DESC
    );

CREATE INDEX blast_trigger_acks_pending_idx
    ON blast_trigger_acks (pending_config_id);

COMMENT ON TABLE blast_trigger_acks IS
    'History of ITB device TriggerStart ARM/DISARM acknowledgments.';

COMMENT ON COLUMN blast_trigger_acks.device_timestamp_utc IS
    'Device-reported UTC timestamp without offset; NULL if clock unset.';

COMMIT;
